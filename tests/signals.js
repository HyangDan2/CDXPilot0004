import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { TRACKS } from "../js/music.js";
import { SIGNALS, signalTracks, restoreSignalSelection, rememberSignalTrack, loadCatalog } from "../js/signals.js";
import { sanitizeSettings, loadSettings, saveSettings } from "../js/settings.js";
import { scoreKey } from "../js/highscores.js";
const catalog = JSON.parse(readFileSync(new URL('../assets/tracks.json', import.meta.url)));
assert.deepEqual(catalog, TRACKS);
for (const [index, signal] of SIGNALS.entries()) {
  assert.equal(signalTracks(catalog, signal).length, 10);
  assert.deepEqual(signalTracks(catalog, signal).map(t => t.id), catalog.slice(index * 10, index * 10 + 10).map(t => t.id));
}
let settings = sanitizeSettings({track: 'event-horizon', lanes: 6, difficulty: 'hard', speed: 8, characterId: 'nova', playMode: 'free'});
Object.assign(settings, restoreSignalSelection(settings, catalog));
assert.equal(settings.signal, 'signal-2', 'Legacy selected track migrates to its signal');
assert.equal(settings.track, 'event-horizon');
Object.assign(settings, restoreSignalSelection(settings, catalog, 'signal-1'));
Object.assign(settings, rememberSignalTrack(settings, catalog[3]));
Object.assign(settings, restoreSignalSelection(settings, catalog, 'signal-2'));
assert.equal(settings.track, 'event-horizon');
Object.assign(settings, restoreSignalSelection(settings, catalog, 'signal-1'));
assert.equal(settings.track, 'deep-orbit');
assert.equal(settings.lanes, 6); assert.equal(settings.difficulty, 'hard');
assert.equal(settings.speed, 8); assert.equal(settings.characterId, 'nova'); assert.equal(settings.playMode, 'free');
const memory = new Map();
globalThis.localStorage = {getItem: k => memory.get(k), setItem: (k,v) => memory.set(k,v)};
saveSettings(settings);
const restored = loadSettings();
assert.deepEqual(restoreSignalSelection(restored, catalog), {signal: 'signal-1', track: 'deep-orbit', signalTracks: {'signal-1':'deep-orbit','signal-2':'event-horizon'}});
assert.equal(restoreSignalSelection(sanitizeSettings({track: 'missing', signal: 'invalid', signalTracks: {'signal-1':'event-horizon'}}), catalog).track, 'neon-galaxy');
assert.equal(restoreSignalSelection(sanitizeSettings({signal:'signal-2', signalTracks:{'signal-2':'missing'}}), catalog).track, 'neon-sprint');
globalThis.localStorage = {getItem() {throw Error('Unavailable');}, setItem() {throw Error('Unavailable');}};
assert.doesNotThrow(() => saveSettings(settings));
assert.equal(restoreSignalSelection(loadSettings(), catalog).track, 'neon-galaxy');
delete globalThis.localStorage;
let request;
assert.deepEqual(await loadCatalog(async (...args) => {request=args; return {ok:true,json:async()=>catalog};}), catalog);
assert(request[0].endsWith('?v=6.2')); assert.equal(request[1].cache,'no-cache');
await assert.rejects(loadCatalog(async()=>({ok:true,json:async()=>catalog.slice(0,10)})), /outdated or incomplete/);
await assert.rejects(loadCatalog(async()=>({ok:false})), /Unable to load/);
const chart = JSON.parse(readFileSync(new URL('../assets/beatmaps/library/event-horizon-6-hard.json', import.meta.url)));
assert.equal(scoreKey(chart,'free'), scoreKey({...chart,signal:'signal-2'},'free'), 'Signal is not part of record identity');
console.log('PASS signals: 10+10 catalog, migration, per-group selection, reload, invalid/storage fallback, preserved settings/record identity and fresh catalog requests');
